// Generate the small, self-hosted icon set from the project's Lucide dependency.
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as icons from 'lucide-react'
import { writeFileSync } from 'node:fs'
const names =
  'Orbit Radio Telescope BookOpen Mouse Crosshair ArrowUpRight ArrowLeft ArrowRight ChevronLeft ChevronRight Compass ScanLine Focus RotateCcw Archive Tags Search Wrench CircleHelp SlidersHorizontal PencilLine UserRound LogIn LogOut X Sun Moon Monitor Library Sparkles Maximize Minimize List Filter FolderOpen Save FileText Plus Trash2 Download Github Check Send AudioLines Box Rotate3D LockKeyhole ExternalLink Copy Clipboard ListTree Eye Image Upload RefreshCw'.split(
    ' ',
  )
const iconSet = Object.fromEntries(
  names.map((n) => [
    n,
    renderToStaticMarkup(
      createElement(icons[n], {
        size: 20,
        strokeWidth: 1.5,
        'aria-hidden': true,
      }),
    ).replace(/ class="[^"]*"/, ''),
  ]),
)
writeFileSync(
  new URL('./icons.js', import.meta.url),
  '// Lucide icons, ISC license. Generated by generate-icons.mjs.\nconst paths = ' +
    JSON.stringify(iconSet) +
    '\nexport const icon = name => paths[name] || "";\n',
)
